#!/usr/bin/env bash
#
# Викладка сайту на сервері (Linux).  Запуск із каталогу проєкту сайту:
#
#   bash deploy.sh              # прод   (pm2-процес, порт і кеш nginx — brand/server.env)
#   bash deploy.sh floy-test    # інший pm2-процес з того ж каталогу (тестовий стенд) — кеш nginx не чіпаємо
#
# Скрипт спільний для всіх сайтів рушія (FLOY-NEW і копії: SMARKET…): усе, чим сайти
# відрізняються на сервері, — у профілі brand/server.env (його ж читає ecosystem.config.cjs).
# Профіль береться той, що лежить на диску до `git pull`: зміна процесу чи порту однаково
# вимагає pm2 delete + pm2 start (DEPLOY.md), тож діє з наступного запуску.
#
# Головне, чого не робить звичайний `nuxi build`: він ЧИСТИТЬ .output, тобто чанки
# попередньої збірки зникають із сервера миттєво. У браузерів, які тримають сторінку
# відкритою (мобільні відновлюють вкладки минулих сеансів постійно), у розмітці записані
# саме старі імена — і дозавантаження шматка коду отримує 404, а сторінка лишається
# напівживою. Тому тут старі чанки повертаються поруч із новими, а протухлі прибираються.
#
# ⚠️ Після рестарту Nitro цих старих файлів НЕ віддає: /_nuxt/* він обслуговує лише за
# переліком, зашитим у збірку (nitropack static.mjs → getAsset), решта — 404. Повернуті
# чанки живуть тільки для старого процесу до рестарту і знадобляться, якщо колись /_nuxt/
# віддаватиме nginx з диска. Від відкритих вкладок рятує plugins/chunk-reload.client.ts.
#
# А от кеш nginx ОБОВ'ЯЗКОВО чистимо після рестарту (кінець скрипта): інакше він до доби
# віддає сторінки зі старими іменами чанків, яких новий процес уже не знає, — сторінка
# приходить без жодного JS. 15.10.2026 так «вмерла» головна: entry-скрипт віддавав 404.
#
# Деталі — у DEPLOY.md, розділ «Оновлення після пушу в GitHub».

set -e

cd "$(dirname "$(readlink -f "$0")")"

# Профіль сайту: APP (бойовий процес), PORT, NGINX_CACHE
if [ -f brand/server.env ]; then
	. brand/server.env
else
	echo "✗ немає brand/server.env — профілю сервера цього сайту" >&2
	exit 1
fi
PROD_APP="$APP"
APP="${1:-$PROD_APP}"
KEEP_DAYS=14
PREV="/tmp/_nuxt-prev-${APP}"

echo "→ каталог: $(pwd), pm2-процес: ${APP}"

# nvm — це shell-функція, у скрипті її треба підключити руками.
# Саме if, а не `[ … ] && …`: під set -e невдала перевірка обірвала б скрипт мовчки.
export NVM_DIR="${NVM_DIR:-$HOME/.nvm}"
if [ -s "$NVM_DIR/nvm.sh" ]; then
	. "$NVM_DIR/nvm.sh"
else
	echo "✗ не знайшов $NVM_DIR/nvm.sh — вкажи NVM_DIR" >&2
	exit 1
fi

git pull

nvm use 22
npm install

# Знімок чанків поточної збірки (-p зберігає дати — за ними працює чистка нижче)
rm -rf "$PREV"
cp -rp .output/public/_nuxt "$PREV" 2>/dev/null || echo "→ попередньої збірки немає, пропускаю"

npx nuxi build

# Повертаємо старі чанки поруч із новими: -n не чіпає щойно зібране, а імена з хешем
# вмісту ніколи не конфліктують
cp -rpn "$PREV/." .output/public/_nuxt/ 2>/dev/null || true
find .output/public/_nuxt -type f -mtime "+${KEEP_DAYS}" -delete
rm -rf "$PREV"

# pm2-демон крутиться на node 16 — команди до нього йдуть саме звідти
nvm use 16
pm2 restart "$APP"

# Кеш nginx — лише для бойового домену (тестовий стенд у нього не пише).
# Спершу чекаємо, поки нова збірка відповідає: інакше в щойно очищений кеш могла б лягти
# відповідь старого процесу. robots.txt Nitro віддає зі своєї статики — це перевірка саме
# процесу, без залежності від API адмінки.
# Теки кешу ще немає (сайт до перемикання домену) — крок пропускається сам
if [ "$APP" = "$PROD_APP" ] && [ -n "$NGINX_CACHE" ] && [ -d "$NGINX_CACHE" ]; then
	for i in $(seq 1 30); do
		if curl -sf -o /dev/null --max-time 5 "http://127.0.0.1:${PORT}/robots.txt"; then break; fi
		sleep 1
	done
	# Саме find, а не rm -rf …/*: nginx пише в кеш просто під час чистки (DEPLOY.md)
	if find "$NGINX_CACHE" -type f -delete; then
		echo "→ кеш nginx очищено"
	else
		echo "✗ не вдалось очистити $NGINX_CACHE — зроби руками: find $NGINX_CACHE -type f -delete" >&2
	fi
fi

echo "→ готово"
