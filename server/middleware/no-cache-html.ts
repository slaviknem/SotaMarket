// HTML-сторінка не має віддаватись із кешу браузера без перевірки.
//
// Nitro не ставить на неї жодного кеш-заголовка, тож браузер (особливо мобільний, який
// відновлює вкладки минулих сеансів) може показати стару розмітку. А в ній — імена чанків
// того білда: після наступної викладки їх на сервері вже немає, дорозвантаження падає 404,
// і сторінка лишається напівживою — саме так зникала маска чохла в конструкторі.
//
// Самі чанки це не зачіпає: їхні імена містять хеш вмісту, і вони й далі віддаються
// з `immutable, max-age=1рік`. Тут — лише документ.

// Усе, що має власні (довгі) заголовки кешу: статика Nuxt, картинки, API
const SKIP = ['/_nuxt/', '/_ipx/', '/api/', '/img/', '/images/', '/fonts/']

export default defineEventHandler((event) => {
	const path = event.path

	if (SKIP.some((prefix) => path.startsWith(prefix))) return
	// Файли з розширенням (robots.txt, favicon, sitemap) — не документи
	if (/\.[a-z0-9]{2,5}($|\?)/i.test(path)) return

	// no-cache, а не no-store: копію тримати можна, але перед показом треба спитати сервер.
	// no-store вимкнув би ще й bfcache, тобто зіпсував би кнопку «назад».
	setResponseHeader(event, 'cache-control', 'no-cache')
})
